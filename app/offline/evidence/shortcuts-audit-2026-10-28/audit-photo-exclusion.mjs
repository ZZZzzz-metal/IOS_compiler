import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve,basename} from 'node:path';
const directory=fileURLToPath(new URL('./',import.meta.url)),root=process.cwd();
const original='C:/Users/20964/AppData/Local/Temp/codex-clipboard-a134fdea-b1d9-44ba-a1aa-e1b570243ad4.jpg';
const bytes=await readFile(original),sha=b=>createHash('sha256').update(b).digest('hex');
const blobId=createHash('sha1').update(Buffer.from('blob '+bytes.length+'\0')).update(bytes).digest('hex');
const objects=execFileSync('git',['rev-list','--objects','--all'],{cwd:root,encoding:'utf8',maxBuffer:100*1024*1024}).trim().split('\n');
const knownObjects=new Set(objects.map(x=>x.split(' ',1)[0]));
assert.equal(knownObjects.has(blobId),false,'User photo content appears in reachable history');
const files=JSON.parse(await readFile(resolve(directory,'git-publication-files.json'),'utf8'));
const matches=files.filter(x=>x.sha256===sha(bytes));assert.equal(matches.length,0,'User photo bytes appear in current publication inventory');
const namedFiles=files.filter(x=>basename(x.path)===basename(original));assert.equal(namedFiles.length,0);
const summary={recordedAt:new Date().toISOString(),specifiedPhotoBasename:basename(original),originalReadOnlyCompared:true,inReachableHistoryByGitBlobId:false,inCurrentPublicationInventoryBySHA256:false,inCurrentPublicationInventoryByFilename:false,matchingFiles:[],scope:'Read-only comparison against the user-provided local photo. The image and its bytes are not copied, embedded or published by this audit. Original content hash is not written to this report.'};
await writeFile(resolve(directory,'photo-exclusion.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify({photoHistoryMatches:0,photoCurrentByteMatches:0,photoCurrentFilenameMatches:0,allPassed:true}));
