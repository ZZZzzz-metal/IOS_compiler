import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const lock = JSON.parse(await readFile(new URL('resources/toolchain.lock.json', root), 'utf8'));
const paths = ['probe.html', 'probe-page.mjs', 'src/compiler-probe.mjs', 'src/compiler-worker.mjs', 'src/toolchain-engine.mjs', 'src/wasm-host.mjs', 'src/wasm-inspect.mjs', 'src/source.mjs', 'src/diagnostics.mjs', 'resources/toolchain.lock.json',
  ...lock.files.map(file => `resources/${lock.vendorDirectory}/${file.filename}`)];
const resources = [];
for (const path of paths) {
  const bytes = await readFile(new URL(path, root));
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const entry = lock.files.find(file => path === `resources/${lock.vendorDirectory}/${file.filename}`);
  if (entry && (bytes.length !== entry.byteLength || sha256 !== entry.sha256)) throw new Error(`Pinned resource mismatch: ${path}`);
  resources.push({ path, byteLength: bytes.length, sha256 });
}
const logic = await readFile(new URL('src/service-worker-template.js', root), 'utf8');
const version = createHash('sha256').update(JSON.stringify(resources)).update(logic).update(await readFile(new URL(import.meta.url))).digest('hex');
const worker = '// Generated by compiler/scripts/build-probe.mjs. Compiler probe scope only.\n' +
  'const CACHE = ' + JSON.stringify('compiler-probe-' + version) + ';\n' +
  'const PREFIX = \'compiler-probe-\';\n' +
  'const RESOURCES = ' + JSON.stringify(resources, null, 2) + ';\n' + logic;
await writeFile(new URL('service-worker.js', root), worker);
await writeFile(new URL('probe-package.json', root), JSON.stringify({ schemaVersion: 1, version, scope: 'compiler-only', byteLength: resources.reduce((n, resource) => n + resource.byteLength, 0), resources }, null, 2) + '\n');
console.log(`Compiler browser probe: ${resources.length} cached files, ${resources.reduce((n, r) => n + r.byteLength, 0)} bytes; ${version}`);
